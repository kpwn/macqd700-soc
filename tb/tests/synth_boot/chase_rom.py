#!/usr/bin/env python3
"""Build a CPU040 ROM chase image, or validate its full-top retirement trace."""

import argparse
from collections import Counter, defaultdict, deque
import hashlib
import json
import subprocess
from pathlib import Path

ROM_BASE = 0x40000000
RING_BASE = ROM_BASE + 0x10000
MASK = 0xFFFFFFFF
SIZES = (2048, 65536)


class JavaRandom:
    def __init__(self, seed):
        self.state = (seed ^ 0x5DEECE66D) & ((1 << 48) - 1)

    def bits(self, count):
        self.state = (self.state * 0x5DEECE66D + 11) & ((1 << 48) - 1)
        return self.state >> (48 - count)

    def next_int(self, bound):
        if bound & (bound - 1) == 0:
            return (bound * self.bits(31)) >> 31
        while True:
            bits = self.bits(31)
            value = bits % bound
            if ((bits - value + bound - 1) & MASK) < 0x80000000:
                return value


def ring(size):
    if size not in SIZES:
        raise ValueError(f"size must be one of {SIZES}")
    nodes = size // 64
    rng = JavaRandom(0x1234567 + size)
    links = list(range(nodes))
    for i in range(nodes - 1, 0, -1):
        j = rng.next_int(i)  # Scala kChaseRing uses Sattolo, not Fisher-Yates.
        links[i], links[j] = links[j], links[i]
    at = 0
    seen = set()
    for _ in range(nodes):
        if at in seen:
            raise AssertionError("ring closes before every node is visited")
        seen.add(at)
        at = links[at]
    if at != 0 or len(seen) != nodes:
        raise AssertionError("ring does not close exactly once")
    return links


def checksum(links):
    value = 0
    for target in links:
        value = ((value << 5) | (value >> 27)) & MASK
        value ^= RING_BASE + 64 * target
    return value


def source(size, links, check):
    nodes = len(links)
    data = "\n".join(
        f"    .long 0x{RING_BASE + 64 * target:08x}\n    .space 60"
        for target in links
    )
    return f"""| Generated by chase_rom.py; {size} byte Sattolo ring.
    .text
    .globl start
    .org 0
vectors:
    .long 0x00500000
    .long start
start:
    move.w #0x2700,%sr
    move.l #0x00ffc000,%d0
    movec %d0,%itt0
    move.l #0x00ffc020,%d0
    movec %d0,%dtt0
    moveq #0,%d0
    movec %d0,%itt1
    movec %d0,%dtt1
    move.l #0x80008000,%d0
    movec %d0,%cacr
    move.l #0x8000,%d0
    movec %d0,%tc

    lea 0x{RING_BASE:08x},%a0
    move.l #{nodes // 4},%d7
    bsr chase
    cmpa.l #0x{RING_BASE:08x},%a0
    bne fail_pc
    move.l #{nodes},%d7
    bsr chase
    cmpa.l #0x{RING_BASE:08x},%a0
    bne fail_pc

    | Validation occurs after the measured end marker.
    lea 0x{RING_BASE:08x},%a1
    move.l #{nodes - 1},%d1
    moveq #0,%d2
checksum_loop:
    rol.l #5,%d2
    move.l (%a1),%d3
    eor.l %d3,%d2
    adda.l #64,%a1
    dbra %d1,checksum_loop
    cmpi.l #0x{check:08x},%d2
    bne fail_pc
pass_pc:
    bra.s pass_pc
fail_pc:
    bra.s fail_pc

chase:
marker_start:
    nop
load_0:
    movea.l (%a0),%a0
load_1:
    movea.l (%a0),%a0
load_2:
    movea.l (%a0),%a0
load_3:
    movea.l (%a0),%a0
    subq.l #1,%d7
    bne.s load_0
marker_end:
    nop
    rts

    .org 0x10000
ring_data:
{data}
"""


def symbols(elf):
    output = subprocess.check_output(["m68k-linux-gnu-nm", "-n", str(elf)], text=True)
    result = {}
    for line in output.splitlines():
        parts = line.split()
        if len(parts) == 3:
            result[parts[2]] = int(parts[0], 16)
    names = ("start", "marker_start", "marker_end", "pass_pc", "fail_pc",
             "ring_data", "load_0", "load_1", "load_2", "load_3")
    missing = set(names) - result.keys()
    if missing:
        raise ValueError(f"ELF lacks symbols: {sorted(missing)}")
    return {name: result[name] for name in names}


def generate(size, out_dir):
    out_dir.mkdir(parents=True, exist_ok=True)
    stem = out_dir / f"chase_{size // 1024}k"
    paths = {ext: stem.with_suffix(f".{ext}") for ext in ("s", "o", "elf", "bin", "json")}
    links = ring(size)
    check = checksum(links)
    paths["s"].write_text(source(size, links, check))
    subprocess.run(["m68k-linux-gnu-as", "-m68040", "-o", str(paths["o"]), str(paths["s"])], check=True)
    subprocess.run(["m68k-linux-gnu-ld", "-Ttext", hex(ROM_BASE), "-e", "start",
                    "-o", str(paths["elf"]), str(paths["o"])], check=True)
    subprocess.run(["m68k-linux-gnu-objcopy", "-O", "binary", str(paths["elf"]), str(paths["bin"])], check=True)
    paths["o"].unlink()
    image = paths["bin"].read_bytes()
    names = symbols(paths["elf"])
    if names["ring_data"] != RING_BASE or len(image) != 0x10000 + size:
        raise AssertionError("ring offset or binary length differs from ROM contract")
    meta = {
        "size_bytes": size, "ring_base": RING_BASE, "nodes": len(links),
        "warm_hops": len(links), "measured_hops": 4 * len(links),
        "measured_marker_occurrence": 2,
        "checksum": check, "rom_sha256": hashlib.sha256(image).hexdigest(),
        "symbols": names, "load_pcs": [names[f"load_{i}"] for i in range(4)],
    }
    paths["json"].write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n")
    del paths["o"]
    return paths


def parse_trace(meta, trace):
    sym = meta["symbols"]
    markers = {name: [] for name in ("marker_start", "marker_end", "pass_pc", "fail_pc")}
    loads = [sym[f"load_{i}"] for i in range(4)]
    if meta["measured_marker_occurrence"] != 2 or meta["load_pcs"] != loads:
        raise ValueError("metadata marker occurrence or load PCs disagree with symbols")
    rows = []
    last_retired = -1
    last_time = -1
    for number, line in enumerate(trace.read_text().splitlines(), 1):
        parts = line.split()
        if len(parts) != 3:
            raise ValueError(f"trace line {number}: expected retired time pc")
        retired, tick, pc = (int(parts[0], 0), int(parts[1], 0), int(parts[2], 0))
        if retired < last_retired or tick < last_time:
            raise ValueError(f"trace line {number}: retire/time order regressed")
        last_retired, last_time = retired, tick
        rows.append((retired, tick, pc))
        for name in markers:
            if pc == sym[name]:
                markers[name].append(len(rows) - 1)
    if len(markers["marker_start"]) != 2 or len(markers["marker_end"]) != 2:
        raise ValueError("expected exactly two start and two end markers")
    s0, s1 = markers["marker_start"]
    e0, e1 = markers["marker_end"]
    if not s0 < e0 < s1 < e1:
        raise ValueError("warm/measured markers are out of order")
    if not markers["pass_pc"] or markers["pass_pc"][0] <= e1 or markers["fail_pc"]:
        raise ValueError("missing post-check pass PC or reached fail PC")
    for first, end, expected in ((s0, e0, meta["warm_hops"]),
                                 (s1, e1, meta["measured_hops"])):
        counts = [sum(row[2] == pc for row in rows[first + 1:end]) for pc in loads]
        if counts != [expected // 4] * 4:
            raise ValueError(f"wrong load PC counts: {counts}, expected {expected // 4} each")
        if rows[end][1] <= rows[first][1]:
            raise ValueError("empty or inverted marker window")
    ticks = rows[e1][1] - rows[s1][1]
    if ticks & 1:
        raise ValueError("window is not an integral number of sysclock cycles")
    cycles = ticks // 2
    return {"cycles": cycles, "hops": meta["measured_hops"],
            "cycles_per_hop": cycles / meta["measured_hops"],
            "warm_start_tick": rows[s0][1], "warm_end_tick": rows[e0][1],
            "start_tick": rows[s1][1], "end_tick": rows[e1][1]}


def parse_bus_trace(path, timing):
    """Check hot-door AXI burst integrity and summarize marker-window traffic."""
    windows = {
        "warm": (timing["warm_start_tick"], timing["warm_end_tick"]),
        "measured": (timing["start_tick"], timing["end_tick"]),
    }
    counts = {window: Counter() for window in windows}
    first_valid = Counter()
    first_transfer = Counter()
    measured_addresses = hashlib.sha256()
    measured_line_reads = 0
    pending = defaultdict(deque)
    last_tick = -1

    def window_at(tick):
        return next((name for name, (start, end) in windows.items()
                     if start < tick <= end), None)

    def number(value):
        return int(value, 0)

    def address(value):
        return int(value, 16)

    for line_no, line in enumerate(path.read_text().splitlines(), 1):
        parts = line.split()
        if not parts:
            continue
        try:
            tick = number(parts[0])
            kind = parts[1]
            if tick < last_tick:
                raise ValueError("bus timestamp regressed")
            last_tick = tick
            window = window_at(tick)
            if kind == "AR" and len(parts) == 7:
                ident, addr, length, size, burst = (number(parts[2]), address(parts[3]),
                                                    number(parts[4]), number(parts[5]),
                                                    number(parts[6]))
                if min(ident, addr, length, size, burst) < 0 or addr > MASK or size > 7 or burst > 3:
                    raise ValueError("invalid AR payload")
                pending[ident].append({"tick": tick, "len": length,
                                       "first_valid": None, "first_transfer": None,
                                       "transfers": 0, "window": window})
                if window:
                    counts[window]["hot_ar"] += 1
                if window == "measured":
                    measured_addresses.update(addr.to_bytes(4, "big"))
                    if length == 0 and size == 4 and burst == 1:
                        measured_line_reads += 1
            elif kind == "RV" and len(parts) == 6:
                ident, resp, last, ready = map(number, parts[2:])
                if not pending[ident]:
                    raise ValueError(f"orphan RV for ID {ident}")
                if resp != 0 or last not in (0, 1) or ready not in (0, 1):
                    raise ValueError("bad RRESP/RLAST/RREADY")
                burst = pending[ident][0]
                if tick < burst["tick"]:
                    raise ValueError("R precedes accepted AR")
                if last != int(burst["transfers"] == burst["len"]):
                    raise ValueError("bad RLAST or beat count")
                if burst["first_valid"] is None:
                    burst["first_valid"] = tick
                if window:
                    counts[window]["hot_r_valid_samples"] += 1
                if ready:
                    if burst["first_transfer"] is None:
                        burst["first_transfer"] = tick
                    burst["transfers"] += 1
                    if window:
                        counts[window]["hot_r_transfers"] += 1
                    if last:
                        if burst["window"] == "measured":
                            for event_tick, histogram in ((burst["first_valid"], first_valid),
                                                          (burst["first_transfer"], first_transfer)):
                                delta = event_tick - burst["tick"]
                                if delta & 1:
                                    raise ValueError("AR-to-R interval is not whole sysclock cycles")
                                histogram[delta // 2] += 1
                        pending[ident].popleft()
            elif kind == "DDR_AR" and len(parts) == 4:
                addr, length = address(parts[2]), number(parts[3])
                if addr < 0 or length < 0:
                    raise ValueError("invalid DDR_AR payload")
                if window:
                    counts[window]["ddr_ar"] += 1
            else:
                raise ValueError("unrecognized bus event or field count")
        except (IndexError, ValueError) as exc:
            raise ValueError(f"bus trace line {line_no}: {exc}") from exc
    if any(pending.values()):
        raise ValueError("bus trace ends with incomplete hot-door AR bursts")
    return {
        "windows": {name: {key: counts[name][key] for key in
                            ("hot_ar", "hot_r_valid_samples", "hot_r_transfers", "ddr_ar")}
                    for name in windows},
        "measured_ar_to_first_rvalid_cycles": dict(sorted(first_valid.items())),
        "measured_ar_to_first_transfer_cycles": dict(sorted(first_transfer.items())),
        "measured_hot_sequence_sha256": measured_addresses.hexdigest(),
        "measured_hot_line_reads": measured_line_reads,
    }


def validate_acceptance(meta, bus, mode):
    if mode != "warmL2":
        raise ValueError(f"unknown acceptance mode: {mode}")
    warm = bus["windows"]["warm"]
    measured = bus["windows"]["measured"]
    if meta["size_bytes"] != 65536 or warm["hot_ar"] == 0 or \
            measured["hot_ar"] == 0 or measured["ddr_ar"] != 0:
        raise ValueError("warmL2 acceptance failed: need 64 KiB, warm/measured hot AR, no measured DDR_AR")
    links = ring(meta["size_bytes"])
    if meta["ring_base"] != RING_BASE or meta["nodes"] != len(links) or \
            meta["measured_hops"] != 4 * len(links):
        raise ValueError("warmL2 acceptance failed: metadata differs from ring contract")
    expected = hashlib.sha256()
    node = 0
    for _ in range(meta["measured_hops"]):
        expected.update((RING_BASE + 64 * node).to_bytes(4, "big"))
        node = links[node]
    if measured["hot_ar"] != meta["measured_hops"] or \
            measured["hot_r_transfers"] != meta["measured_hops"] or \
            bus.get("measured_hot_line_reads") != meta["measured_hops"] or \
            bus.get("measured_hot_sequence_sha256") != expected.hexdigest():
        raise ValueError("warmL2 acceptance failed: measured pointer request sequence or line-read shape differs")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    build = commands.add_parser("generate")
    build.add_argument("--size", type=int, choices=SIZES, required=True)
    build.add_argument("--out-dir", type=Path, required=True)
    check = commands.add_parser("parse")
    check.add_argument("--meta", type=Path, required=True)
    check.add_argument("--trace", type=Path, required=True)
    check.add_argument("--rom", type=Path, help="verify trace is paired with this ROM image")
    check.add_argument("--bus-trace", type=Path, help="optional hot-door/L2 bus events")
    check.add_argument("--acceptance", choices=("warmL2",),
                       help="require a complete 64 KiB warm-L2 measurement")
    args = parser.parse_args()
    if args.command == "generate":
        print(json.dumps({key: str(value) for key, value in generate(args.size, args.out_dir).items()}, indent=2))
    else:
        meta = json.loads(args.meta.read_text())
        if args.rom and hashlib.sha256(args.rom.read_bytes()).hexdigest() != meta["rom_sha256"]:
            raise ValueError("ROM image SHA-256 differs from metadata")
        result = parse_trace(meta, args.trace)
        if args.acceptance and not args.bus_trace:
            raise ValueError("warmL2 acceptance requires --bus-trace")
        if args.bus_trace:
            result["bus"] = parse_bus_trace(args.bus_trace, result)
        if args.acceptance == "warmL2":
            validate_acceptance(meta, result["bus"], args.acceptance)
        print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
