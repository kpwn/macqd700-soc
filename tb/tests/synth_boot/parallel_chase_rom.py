#!/usr/bin/env python3
"""Generate and validate a four-chain CPU040 warm-L2 ROM benchmark."""
import argparse
import hashlib
import json
import subprocess
from collections import defaultdict, deque, Counter
from pathlib import Path
import chase_rom as single

CHAINS = 4
SIZE = 65536
NODES = SIZE // 64
PER_CHAIN = NODES // CHAINS


def ring():
    links = []
    for chain in range(CHAINS):
        rng = single.JavaRandom(0x1234567 + SIZE + chain)
        local = list(range(PER_CHAIN))
        for i in range(PER_CHAIN - 1, 0, -1):
            j = rng.next_int(i)
            local[i], local[j] = local[j], local[i]
        links.extend(chain * PER_CHAIN + target for target in local)
    for chain in range(CHAINS):
        start = chain * PER_CHAIN
        at, seen = start, set()
        for _ in range(PER_CHAIN):
            if at in seen or at // PER_CHAIN != chain:
                raise ValueError('chain is not a complete independent cycle')
            seen.add(at)
            at = links[at]
        if at != start:
            raise ValueError('chain does not close')
    return links


def source(links):
    text = single.source(SIZE, links, single.checksum(links))
    initial = '\n'.join(f'    lea 0x{single.RING_BASE + c * PER_CHAIN * 64:08x},%a{c}' for c in range(CHAINS))
    text = text.replace(f'    lea 0x{single.RING_BASE:08x},%a0', initial, 1)
    old = f'    cmpa.l #0x{single.RING_BASE:08x},%a0\n    bne fail_pc'
    checks = '\n'.join(f'    cmpa.l #0x{single.RING_BASE + c * PER_CHAIN * 64:08x},%a{c}\n    bne fail_pc' for c in range(CHAINS))
    if text.count(old) != 2:
        raise ValueError('single-chain template changed pointer checks')
    text = text.replace(old, checks)
    for c in range(CHAINS):
        old = f'load_{c}:\n    movea.l (%a0),%a0'
        if text.count(old) != 1:
            raise ValueError('single-chain template changed load labels')
        text = text.replace(old, f'load_{c}:\n    movea.l (%a{c}),%a{c}')
    return text.replace('Generated by chase_rom.py;', 'Generated by parallel_chase_rom.py; four independent chains;')


def generate(out):
    out.mkdir(parents=True, exist_ok=True)
    stem = out / 'parallel_chase_4x16k'
    paths = {ext: stem.with_suffix('.' + ext) for ext in ('s', 'o', 'elf', 'bin', 'json')}
    links = ring()
    paths['s'].write_text(source(links))
    subprocess.run(['m68k-linux-gnu-as', '-m68040', '-o', str(paths['o']), str(paths['s'])], check=True)
    subprocess.run(['m68k-linux-gnu-ld', '-Ttext', hex(single.ROM_BASE), '-e', 'start', '-o', str(paths['elf']), str(paths['o'])], check=True)
    subprocess.run(['m68k-linux-gnu-objcopy', '-O', 'binary', str(paths['elf']), str(paths['bin'])], check=True)
    paths.pop('o').unlink()
    image = paths['bin'].read_bytes()
    names = single.symbols(paths['elf'])
    if names['ring_data'] != single.RING_BASE or len(image) != 0x10000 + SIZE:
        raise ValueError('unexpected ROM shape')
    meta = dict(size_bytes=SIZE, ring_base=single.RING_BASE, nodes=NODES,
                chains=CHAINS, nodes_per_chain=PER_CHAIN, warm_hops=NODES,
                measured_hops=4*NODES, measured_marker_occurrence=2,
                checksum=single.checksum(links), rom_sha256=hashlib.sha256(image).hexdigest(),
                symbols=names, load_pcs=[names[f'load_{i}'] for i in range(CHAINS)])
    paths['json'].write_text(json.dumps(meta, indent=2, sort_keys=True)+'\n')
    return paths


def validate_requests(path, timing):
    # A retirement marker is not an issue fence. Classify each chain's full
    # warm+measured request prefix, including requests issued before the marker.
    links = ring()
    next_node = [c * PER_CHAIN for c in range(CHAINS)]
    counts = [0] * CHAINS
    pending = defaultdict(deque)
    inflight, peak, transfers, preissued = 0, 0, 0, 0
    latency = Counter()
    digest = hashlib.sha256()
    for line in path.read_text().splitlines():
        row = line.split()
        if not row:
            continue
        tick = int(row[0], 0)
        if tick > timing['end_tick']:
            break
        if row[1] == 'AR':
            ident, addr = int(row[2], 0), int(row[3], 16)
            offset = addr - single.RING_BASE
            measured = False
            if 0 <= offset < SIZE:
                if offset % 64:
                    raise ValueError('pointer request outside aligned table nodes')
                node = offset // 64
                chain = node // PER_CHAIN
                if counts[chain] < 5 * PER_CHAIN:
                    if node != next_node[chain]:
                        raise ValueError(f'chain {chain} skipped or repeated a pointer step')
                    if tuple(int(x, 0) for x in row[4:]) != (0, 4, 1):
                        raise ValueError('pointer request is not one 16-byte line')
                    next_node[chain] = links[node]
                    measured = counts[chain] >= PER_CHAIN
                    counts[chain] += 1
                    if measured:
                        digest.update(addr.to_bytes(4, 'big'))
                        inflight += 1
                        peak = max(peak, inflight)
                        preissued += tick <= timing['start_tick']
            pending[ident].append((tick, measured))
        elif row[1] == 'RV' and int(row[5], 0) and int(row[4], 0):
            ident = int(row[2], 0)
            if not pending[ident]:
                raise ValueError('response without request')
            issued, measured = pending[ident].popleft()
            if measured:
                if int(row[3], 0) or (tick-issued) % 2:
                    raise ValueError('bad measured response')
                inflight -= 1
                transfers += 1
                latency[(tick-issued)//2] += 1
    if counts != [5*PER_CHAIN]*CHAINS or next_node != [c*PER_CHAIN for c in range(CHAINS)] or inflight or transfers != 4*NODES:
        raise ValueError('incomplete warm/measured chain prefix or responses before retirement end')
    return dict(pointer_reads_per_chain=[4*PER_CHAIN]*CHAINS,
                warm_pointer_reads_per_chain=[PER_CHAIN]*CHAINS,
                measured_requests_before_start_marker=preissued,
                phase_ar_to_transfer_cycles=dict(sorted(latency.items())),
                phase_request_sha256=digest.hexdigest(),
                max_outstanding_hot_reads=peak)


def parse(meta_path, rom, trace, bus):
    meta = json.loads(meta_path.read_text())
    if (meta.get('chains'), meta.get('nodes_per_chain'), meta.get('size_bytes'),
        meta.get('nodes'), meta.get('ring_base'), meta.get('warm_hops'), meta.get('measured_hops')) != (
        CHAINS, PER_CHAIN, SIZE, NODES, single.RING_BASE, NODES, 4*NODES):
        raise ValueError('metadata differs from four-chain contract')
    if hashlib.sha256(rom.read_bytes()).hexdigest() != meta['rom_sha256']:
        raise ValueError('ROM hash mismatch')
    result = single.parse_trace(meta, trace)
    result['bus'] = single.parse_bus_trace(bus, result)
    traffic = result['bus']['windows']['measured']
    if traffic['ddr_ar'] != 0:
        raise ValueError('measured retirement window contains DDR reads')
    if result['bus']['windows']['warm']['hot_ar'] == 0:
        raise ValueError('missing warmup requests')
    result['parallel'] = validate_requests(bus, result)
    result['bytes_per_cycle'] = result['hops'] * 4 / result['cycles']
    return result


def main():
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest='command', required=True)
    gen = sub.add_parser('generate')
    gen.add_argument('--out-dir', type=Path, required=True)
    check = sub.add_parser('parse')
    for name in ('meta', 'rom', 'trace', 'bus-trace'):
        check.add_argument('--'+name, type=Path, required=True)
    args = p.parse_args()
    result = {k: str(v) for k,v in generate(args.out_dir).items()} if args.command == 'generate' else parse(args.meta, args.rom, args.trace, args.bus_trace)
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
